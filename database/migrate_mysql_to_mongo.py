"""
Migrate ReviewLens v1 (MySQL) accounts and datasets to ReviewLens 2.0 (MongoDB).

Strategy - safe and repeatable:
  * users are copied with their existing BCrypt password hashes (everyone keeps their password; role USER);
  * dataset metadata is copied and each dataset is QUEUED for re-analysis from its original uploaded CSV,
    so reviews, aspect results and keywords are regenerated by the current engine (no fragile remapping of
    millions of numeric ids);
  * users whose email already exists and datasets whose file is already registered are skipped;
  * DRY RUN by default - nothing is written unless --execute is given.

Usage (run from the project root, with the v2 backend stopped or running - it picks up queued jobs):
  pip install pymysql pymongo
  python database/migrate_mysql_to_mongo.py --mysql-user root --mysql-password <pw> --uploads backend/uploads
  python database/migrate_mysql_to_mongo.py --mysql-user root --mysql-password <pw> --uploads backend/uploads --execute

MongoDB connection: --mongo-uri / --mongo-db, or MONGODB_URI / MONGODB_DATABASE from the environment.
"""
from __future__ import annotations

import argparse
import os
import sys
from datetime import datetime, timezone
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mysql-host", default="localhost")
    ap.add_argument("--mysql-port", type=int, default=3306)
    ap.add_argument("--mysql-user", default="root")
    ap.add_argument("--mysql-password", default=os.environ.get("DB_PASSWORD", ""))
    ap.add_argument("--mysql-db", default="reviewlens")
    ap.add_argument("--mongo-uri", default=os.environ.get("MONGODB_URI", "mongodb://localhost:27017"))
    ap.add_argument("--mongo-db", default=os.environ.get("MONGODB_DATABASE", "reviewlens"))
    ap.add_argument("--uploads", default="backend/uploads", help="folder that contains the v1 uploaded CSV files")
    ap.add_argument("--execute", action="store_true", help="actually write to MongoDB (default: dry run)")
    a = ap.parse_args()

    try:
        import pymysql
        from bson import ObjectId
        from pymongo import MongoClient
    except ImportError:
        print("Install the dependencies first:  pip install pymysql pymongo")
        return 2

    src = pymysql.connect(host=a.mysql_host, port=a.mysql_port, user=a.mysql_user, password=a.mysql_password,
                          database=a.mysql_db, cursorclass=pymysql.cursors.DictCursor)
    db = MongoClient(a.mongo_uri, serverSelectionTimeoutMS=5000)[a.mongo_db]
    db.command("ping")
    mode = "EXECUTE" if a.execute else "DRY RUN"
    print(f"[{mode}] MySQL {a.mysql_host}/{a.mysql_db}  ->  MongoDB database '{a.mongo_db}'")

    now = datetime.now(timezone.utc)
    id_map: dict[int, ObjectId] = {}
    stats = {"users_copied": 0, "users_skipped": 0, "datasets_queued": 0, "datasets_skipped": 0}

    with src.cursor() as cur:
        cur.execute("SELECT id, name, email, password_hash, created_at FROM users")
        for u in cur.fetchall():
            email = (u["email"] or "").strip().lower()
            existing = db.users.find_one({"email": email}, {"_id": 1})
            if existing:
                id_map[u["id"]] = existing["_id"]
                stats["users_skipped"] += 1
                print(f"  user {email}: already exists - skipped")
                continue
            doc = {"_id": ObjectId(), "name": u["name"], "email": email, "passwordHash": u["password_hash"],
                   "role": "USER", "active": True, "tokenVersion": 0,
                   "createdAt": u["created_at"].replace(tzinfo=timezone.utc) if u["created_at"] else now}
            id_map[u["id"]] = doc["_id"]
            if a.execute:
                db.users.insert_one(doc)
            stats["users_copied"] += 1
            print(f"  user {email}: {'copied' if a.execute else 'would be copied'}")

        cur.execute("SELECT id, owner_id, name, file_name, stored_path, created_at FROM datasets")
        for d in cur.fetchall():
            path = Path(d["stored_path"] or "")
            if not path.is_file():
                candidate = Path(a.uploads) / path.name
                path = candidate if candidate.is_file() else path
            owner = id_map.get(d["owner_id"])
            if owner is None or not path.is_file():
                stats["datasets_skipped"] += 1
                print(f"  dataset '{d['name']}': {'owner not migrated' if owner is None else 'upload file not found'} - skipped")
                continue
            if db.datasets.find_one({"storedPath": str(path.resolve())}, {"_id": 1}):
                stats["datasets_skipped"] += 1
                print(f"  dataset '{d['name']}': already registered - skipped")
                continue
            ds_id, job_id = ObjectId(), ObjectId()
            dataset = {"_id": ds_id, "ownerId": owner, "name": d["name"], "fileName": d["file_name"],
                       "fileSize": path.stat().st_size, "storedPath": str(path.resolve()), "status": "QUEUED",
                       "totalReviews": 0, "processedReviews": 0, "skippedRows": 0, "productCount": 0,
                       "duplicateReviews": 0, "mappingOverridden": False, "latestJobId": job_id,
                       "createdAt": d["created_at"].replace(tzinfo=timezone.utc) if d["created_at"] else now}
            job = {"_id": job_id, "datasetId": ds_id, "datasetName": d["name"], "ownerId": owner, "triggeredBy": owner,
                   "type": "INITIAL", "status": "QUEUED", "stage": "QUEUED", "totalReviews": 0,
                   "processedReviews": 0, "createdAt": now, "nlpEngine": "migrated-from-v1"}
            if a.execute:
                db.datasets.insert_one(dataset)
                db.analysisJobs.insert_one(job)
            stats["datasets_queued"] += 1
            print(f"  dataset '{d['name']}': {'queued for re-analysis' if a.execute else 'would be queued for re-analysis'}")

    print("\nSummary:", ", ".join(f"{k}={v}" for k, v in stats.items()))
    if not a.execute:
        print("Dry run only - re-run with --execute to write these changes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
